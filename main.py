def _collecter(code: str, commune: dict, profondeur: int, fenetre: int, seuil: int) -> dict:
    travail = TRAVAUX[code]
    resultat: dict = {"commune": commune}

    travail["etape"] = "Populations légales (Insee)"
    resultat["population"] = population.analyse(code, commune.get("population"))

    travail["etape"] = "Ventes immobilières (DVF — DGFiP)"
    try:
        annees = dvf.annees_disponibles(code, profondeur=profondeur)
        ventes = dvf.preparer(dvf.charger(code, annees))
        resultat["annees"] = annees
        resultat["ventes"] = ventes
        resultat["erreur_dvf"] = None
    except SourceError as exc:
        resultat["ventes"] = pd.DataFrame()
        resultat["annees"] = []
        resultat["erreur_dvf"] = str(exc)

    ventes = resultat["ventes"]
    travail["etape"] = "Prix au m² et typologies"
    resultat["table_prix"] = dvf.prix_par_annee(ventes) if not ventes.empty else pd.DataFrame()
    resultat["evolution_prix"] = (
        dvf.evolution_prix(resultat["table_prix"], recul=3) if not resultat["table_prix"].empty else None
    )
    resultat["evolution_appartement"] = (
        dvf.evolution_prix(resultat["table_prix"], recul=3, colonne="prix_m2_median_appartement")
        if not resultat["table_prix"].empty
        else None
    )
    resultat["evolution_maison"] = (
        dvf.evolution_prix(resultat["table_prix"], recul=3, colonne="prix_m2_median_maison")
        if not resultat["table_prix"].empty
        else None
    )
    resultat["demande"] = (
        demande.analyser(ventes, mois=fenetre, seuil_ventes=seuil) if not ventes.empty else pd.DataFrame()
    )
    resultat["synthese_demande"] = (
        demande.synthese(resultat["demande"]) if not resultat["demande"].empty else {}
    )
    resultat["couverture"] = dvf.couverture(ventes)
    resultat["fenetre"] = fenetre

    travail["etape"] = "Actualité locale et équipements"
    try:
        resultat["actualites"] = actualite.actualites(commune["nom"], commune.get("codeDepartement"), 24)
    except SourceError as exc:
        resultat["actualites"] = {"themes": {}, "erreurs": [str(exc)]}
    try:
        resultat["ecoles"] = actualite.equipements_scolaires(code)
    except SourceError:
        resultat["ecoles"] = None

    resultat["horodatage"] = dt.datetime.now()
    return resultat


def _executer(code: str, commune: dict, profondeur: int, fenetre: int, seuil: int) -> None:
    try:
        donnees = _collecter(code, commune, profondeur, fenetre, seuil)
        with VERROU:
            TRAVAUX[code].update({"statut": "pret", "donnees": donnees, "etape": "Terminé"})
    except Exception as exc:  # noqa: BLE001 - toute panne doit remonter a l'ecran
        with VERROU:
            TRAVAUX[code].update({"statut": "erreur", "message": str(exc), "etape": "Interrompu"})


def lancer(code: str, commune: dict, profondeur: int = 6, fenetre: int = 24, seuil: int = 5) -> dict:
    """Demarre (ou reutilise) l'analyse d'une commune."""
    with VERROU:
        travail = TRAVAUX.get(code)
        if travail:
            frais = (
                travail.get("statut") == "pret"
                and travail["donnees"]["horodatage"] > dt.datetime.now() - DUREE_VALIDITE
                and travail.get("parametres") == (profondeur, fenetre, seuil)
            )
            if frais or travail.get("statut") == "en_cours":
                return travail
        TRAVAUX[code] = {
            "statut": "en_cours",
            "etape": "Initialisation",
            "commune": commune,
            "parametres": (profondeur, fenetre, seuil),
            "debut": dt.datetime.now(),
        }
    EXECUTEUR.submit(_executer, code, commune, profondeur, fenetre, seuil)
    return TRAVAUX[code]


