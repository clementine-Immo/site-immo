def _euros(valeur, suffixe: str = "") -> str:
    if valeur is None or (isinstance(valeur, float) and pd.isna(valeur)):
        return "n.d."
    return f"{valeur:,.0f}".replace(",", " ") + f" €{suffixe}"


def _nombre(valeur) -> str:
    if valeur is None or (isinstance(valeur, float) and pd.isna(valeur)):
        return "n.d."
    return f"{valeur:,.0f}".replace(",", " ")


def _contexte_ville(donnees: dict) -> dict:
    pop = donnees["population"]
    table_prix = donnees["table_prix"]
    demande_table = donnees["demande"]

    serie_pop = pop.get("serie") or {}
    graphe_population = graphiques.courbe(
        [{"nom": "Population municipale", "points": [(a, v) for a, v in sorted(serie_pop.items())]}],
        titre_accessible="Évolution de la population municipale",
    )

    series_prix = []
    if not table_prix.empty:
        for nom, colonne, couleur in (
            ("Appartement", "prix_m2_median_appartement", graphiques.SERIE_1),
            ("Maison", "prix_m2_median_maison", graphiques.SERIE_2),
        ):
            points = [
                (int(ligne["annee"]), float(ligne[colonne]))
                for _, ligne in table_prix.iterrows()
                if pd.notna(ligne.get(colonne))
            ]
            if len(points) >= 2:
                series_prix.append({"nom": nom, "points": points, "couleur": couleur})
        if not series_prix:
            points = [
                (int(ligne["annee"]), float(ligne["prix_m2_median"]))
                for _, ligne in table_prix.iterrows()
                if pd.notna(ligne["prix_m2_median"])
            ]
            if len(points) >= 2:
                series_prix.append({"nom": "Tous biens", "points": points})
    graphe_prix = graphiques.courbe(
        series_prix, unite=" €", titre_accessible="Évolution du prix médian au m²"
    )

    classees = demande_table[demande_table["retenu"]] if not demande_table.empty else pd.DataFrame()
    graphe_demande = graphiques.barres(
        [
            {"libelle": ligne["segment"], "valeur": round(float(ligne["score_demande"]), 1)}
            for _, ligne in classees.iterrows()
        ]
        if not classees.empty
        else []
    )
    graphe_volumes = graphiques.barres(
        [
            {"libelle": ligne["segment"], "valeur": int(ligne["ventes_recentes"]), "couleur": "#5A6472"}
            for _, ligne in classees.iterrows()
        ]
        if not classees.empty
        else []
    )

    lignes_prix = []
    if not table_prix.empty:
        for _, ligne in table_prix.iterrows():
            lignes_prix.append(
                {
                    "annee": int(ligne["annee"]),
                    "ventes": int(ligne["ventes"]),
                    "median": _euros(ligne["prix_m2_median"], "/m²"),
                    "moyen": _euros(ligne["prix_m2_moyen"], "/m²"),
                    "appartement": _euros(ligne.get("prix_m2_median_appartement"), "/m²"),
                    "maison": _euros(ligne.get("prix_m2_median_maison"), "/m²"),
                    "prix_bien": _euros(ligne["prix_median"]),
                    "surface": f"{ligne['surface_mediane']:.0f} m²" if pd.notna(ligne["surface_mediane"]) else "n.d.",
                }
            )

    lignes_demande = []
    if not demande_table.empty:
        for _, ligne in demande_table.iterrows():
            lignes_demande.append(
                {
                    "segment": ligne["segment"],
                    "classee": bool(ligne["retenu"]),
                    "score": f"{ligne['score_demande']:.0f}" if pd.notna(ligne["score_demande"]) else "—",
                    "ventes": int(ligne["ventes_recentes"]),
                    "part": f"{ligne['part_marche_pct']:.1f} %" if pd.notna(ligne["part_marche_pct"]) else "n.d.",
                    "volume": graphiques.variation(
                        float(ligne["evolution_volume_pct"]) if pd.notna(ligne["evolution_volume_pct"]) else None
                    ),
                    "prix_m2": _euros(ligne["prix_m2_median"], "/m²"),
                    "prix_bien": _euros(ligne["prix_median"]),
                    "surface": f"{ligne['surface_mediane']:.0f} m²" if pd.notna(ligne["surface_mediane"]) else "n.d.",
                    "evolution_prix": graphiques.variation(
                        float(ligne["evolution_prix_m2_3ans_pct"])
                        if pd.notna(ligne["evolution_prix_m2_3ans_pct"])
                        else None
                    ),
                }
            )

    synthese = donnees.get("synthese_demande") or {}
    plus = synthese.get("plus_demandes")
    moins = synthese.get("moins_demandes")

    def _resume(table):
        if table is None or table.empty:
            return []
        return [
            {
                "segment": ligne["segment"],
                "score": f"{ligne['score_demande']:.0f}",
                "commentaire": demande.commentaire(ligne),
                "prix_m2": _euros(ligne["prix_m2_median"], "/m²"),
            }
            for _, ligne in table.iterrows()
        ]

    derniere = table_prix.iloc[-1] if not table_prix.empty else None
    return {
        "commune": donnees["commune"],
        "population": pop,
        "population_actuelle": _nombre(pop.get("population_actuelle")),
        "court_terme": pop.get("court_terme"),
        "moyen_terme": pop.get("moyen_terme"),
        "prix_median": _euros(derniere["prix_m2_median"], "/m²") if derniere is not None else "n.d.",
        "annee_prix": int(derniere["annee"]) if derniere is not None else None,
        "ventes_annee": int(derniere["ventes"]) if derniere is not None else 0,
        "evolution_prix": donnees["evolution_prix"],
        "evolution_appartement": donnees["evolution_appartement"],
        "evolution_maison": donnees["evolution_maison"],
        "graphe_population": graphe_population,
        "graphe_prix": graphe_prix,
        "graphe_demande": graphe_demande,
        "graphe_volumes": graphe_volumes,
        "lignes_prix": lignes_prix,
        "lignes_demande": lignes_demande,
        "plus_demandes": _resume(plus),
        "moins_demandes": _resume(moins),
        "serie_population": sorted(serie_pop.items()),
        "actualites": donnees["actualites"],
        "ecoles": donnees["ecoles"],
        "couverture": donnees["couverture"],
        "annees": donnees["annees"],
        "erreur_dvf": donnees["erreur_dvf"],
        "fenetre": donnees["fenetre"],
        "variation": graphiques.variation,
        "horodatage": donnees["horodatage"],
    }


