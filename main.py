@app.get("/ville/{code}", response_class=HTMLResponse)
def ville(request: Request, code: str, profondeur: int = 6, fenetre: int = 24, seuil: int = 5):
    try:
        commune = geo.par_code(code)
    except SourceError as exc:
        return gabarits.TemplateResponse(
            request,
            "erreur.html",
            {"nom_site": NOM_SITE, "baseline": BASELINE, "message": str(exc), "page": "recherche"},
            status_code=503,
        )
    travail = lancer(code, commune, profondeur, fenetre, seuil)
    contexte = {
        "nom_site": NOM_SITE,
        "baseline": BASELINE,
        "commune": commune,
        "code": code,
        "page": "ville",
        "statut": travail["statut"],
        "etape": travail.get("etape"),
        "fenetre": fenetre,
        "profondeur": profondeur,
        "seuil": seuil,
    }
    if travail["statut"] == "pret":
        contexte.update(_contexte_ville(travail["donnees"]))
    return gabarits.TemplateResponse(request, "ville.html", contexte)


@app.get("/api/ville/{code}")
def api_ville(request: Request, code: str):
    travail = TRAVAUX.get(code)
    if not travail:
        return JSONResponse({"statut": "inconnu"}, status_code=404)
    if travail["statut"] == "en_cours":
        return {"statut": "en_cours", "etape": travail.get("etape")}
    if travail["statut"] == "erreur":
        return {"statut": "erreur", "message": travail.get("message")}
    contexte = _contexte_ville(travail["donnees"])
    contexte.update({"request": request, "code": code, "nom_site": NOM_SITE, "page": "ville"})
    fragment = gabarits.get_template("contenu.html").render(contexte)
    return {"statut": "pret", "html": fragment}


@app.get("/ville/{code}/export.xlsx")
def exporter(code: str):
    travail = TRAVAUX.get(code)
    if not travail or travail["statut"] != "pret":
        return JSONResponse({"erreur": "Analyse non terminée"}, status_code=409)
    donnees = travail["donnees"]
    contenu = export.classeur(
        donnees["commune"],
        donnees["population"],
        donnees["table_prix"],
        donnees["demande"],
        donnees["ventes"],
        donnees["actualites"],
    )
    nom = f"analyse_{donnees['commune']['nom'].lower().replace(' ', '_')}_{dt.date.today():%Y%m%d}.xlsx"
    return Response(
        content=contenu,
        media_type="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
        headers={"Content-Disposition": f'attachment; filename="{nom}"'},
    )


